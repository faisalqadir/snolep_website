"""Turn the snow leopard reference sheet into dot frames for js/leopard-frames.js.

    python3 tools/leopard-frames.py tools/leopard-reference.webp js/leopard-frames.js

The sheet is three rows of three side views on ground lines. Each frame is cut out, lined up on
its head and its ground line, filled to a silhouette, and sampled on one shared grid of dots: a
cell is ink (a dark dot, sized by how dark the drawing is there), coat (a small light dot inside
the silhouette) or empty. Needs numpy, scipy, Pillow.
"""
import sys, json, base64
import numpy as np
from PIL import Image
from scipy import ndimage as nd

SRC, OUT = sys.argv[1], sys.argv[2]
GROUNDS = [313, 622, 920]
COLS = [(0, 540), (540, 1080), (1080, 1620)]
# frames in the order the page uses: stand, then the gallop cycle (stretched, front reach, hind
# coming under, gathered, hind landing, push off); the stretched one is also the leap
ORDER = [0, 1, 5, 2, 8, 7, 4]
CELLS = int(sys.argv[3]) if len(sys.argv) > 3 else 4400

g = np.asarray(Image.open(SRC).convert('L')).astype(float)
frames = []
for k in ORDER:
    r, c = divmod(k, 3)
    sub = g[GROUNDS[r] - 290:GROUNDS[r] - 3, COLS[c][0]:COLS[c][1]]
    ink = sub < 200
    ys, xs = np.nonzero(ink)
    x0, x1 = xs.min(), xs.max()
    left = ink[:, : x0 + int((x1 - x0) * 0.4)]
    top = np.nonzero(left.any(1))[0].min()
    head = np.nonzero(left[top:top + 50].any(0))[0].min()
    sil = nd.binary_erosion(nd.binary_fill_holes(nd.binary_dilation(ink, iterations=7)), iterations=6)
    sil |= ink
    dark = np.clip((235 - sub) / 170, 0, 1)
    frames.append((head, sub.shape[0], dark, sil))

ANCHOR = 190          # source px from the head back to the middle of the body: the turning point

def sample(pitch):
    cells = {}
    for fi, (head, ground, dark, sil) in enumerate(frames):
        H, W = dark.shape
        for gy in range(int(-ground / pitch) - 1, 1):
            for gx in range(int((-head - ANCHOR) / pitch) - 1, int((W - head - ANCHOR) / pitch) + 2):
                x0 = int(round(head + ANCHOR + gx * pitch)); y0 = int(round(ground + gy * pitch - pitch))
                x1, y1 = x0 + int(round(pitch)), y0 + int(round(pitch))
                if x0 < 0 or y0 < 0 or x1 > W or y1 > H: continue
                d = dark[y0:y1, x0:x1].mean(); s = sil[y0:y1, x0:x1].mean()
                if d > 0.2: v = 128 + int(min(127, 40 + d * 160))
                elif s > 0.5: v = 60
                else: continue
                cells.setdefault((gx, gy), [0] * len(frames))[fi] = v
    return cells

lo, hi = 2.0, 12.0
for _ in range(30):
    mid = (lo + hi) / 2
    if len(sample(mid)) > CELLS: lo = mid
    else: hi = mid
pitch = hi
cells = sample(pitch)
keys = sorted(cells, key=lambda k: (k[1], k[0]))
xs = np.array([k[0] for k in keys], np.int8); ys = np.array([k[1] for k in keys], np.int8)
vals = np.array([[cells[k][f] for k in keys] for f in range(len(frames))], np.uint8)
blob = lambda a: base64.b64encode(a.tobytes()).decode()
js = ('// Generated by tools/leopard-frames.py from tools/leopard-reference.webp. Do not edit.\n'
      f'export const PITCH = {pitch:.4f};\nexport const COUNT = {len(keys)};\nexport const FRAMES = {len(frames)};\n'
      f'export const GX = "{blob(xs)}";\nexport const GY = "{blob(ys)}";\nexport const V = "{blob(vals)}";\n')
open(OUT, 'w').write(js)
print('pitch', round(pitch, 3), 'cells', len(keys), 'bytes', len(js), 'per frame', [(int((vals[f] > 0).sum())) for f in range(len(frames))])
