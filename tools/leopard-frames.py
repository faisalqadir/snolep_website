"""Turn the snow leopard reference sheet into dot frames for js/leopard-frames.js.

    python3 tools/leopard-frames.py tools/leopard-reference.webp js/leopard-frames.js

The sheet is three rows of three side views on ground lines. Each frame is cut out, lined up on
its head and its ground line, filled to a silhouette, and sampled on one grid of dots: a cell is ink (a dark
dot, sized by how dark the drawing is there), coat (a small light dot inside the silhouette) or
empty. Then the dots are matched across frames so each one can glide from pose to pose. Needs
numpy, scipy, Pillow.
"""
import sys, json, base64
import numpy as np
from PIL import Image
from scipy import ndimage as nd

SRC, OUT = sys.argv[1], sys.argv[2]
GROUNDS = [313, 622, 920]
COLS = [(0, 540), (540, 1080), (1080, 1620)]
# frames in the order the page uses: stand, then the gallop cycle (stretched, front reach, hind
# coming under, gathered, hind landing, push off); the stretched one is also the leap
ORDER = [0, 1, 5, 2, 8, 7, 4]
CELLS = int(sys.argv[3]) if len(sys.argv) > 3 else 2600

g = np.asarray(Image.open(SRC).convert('L')).astype(float)
frames = []
for k in ORDER:
    r, c = divmod(k, 3)
    sub = g[GROUNDS[r] - 290:GROUNDS[r] - 3, COLS[c][0]:COLS[c][1]]
    ink = sub < 200
    ys, xs = np.nonzero(ink)
    x0, x1 = xs.min(), xs.max()
    left = ink[:, : x0 + int((x1 - x0) * 0.4)]
    top = np.nonzero(left.any(1))[0].min()
    head = np.nonzero(left[top:top + 50].any(0))[0].min()
    sil = nd.binary_erosion(nd.binary_fill_holes(nd.binary_dilation(ink, iterations=7)), iterations=6)
    sil |= ink
    dark = np.clip((235 - sub) / 170, 0, 1)
    frames.append((head, sub.shape[0], dark, sil))

ANCHOR = 190          # source px from the head back to the middle of the body: the turning point

def sample(pitch):
    cells = {}
    for fi, (head, ground, dark, sil) in enumerate(frames):
        H, W = dark.shape
        for gy in range(int(-ground / pitch) - 1, 1):
            for gx in range(int((-head - ANCHOR) / pitch) - 1, int((W - head - ANCHOR) / pitch) + 2):
                x0 = int(round(head + ANCHOR + gx * pitch)); y0 = int(round(ground + gy * pitch - pitch))
                x1, y1 = x0 + int(round(pitch)), y0 + int(round(pitch))
                if x0 < 0 or y0 < 0 or x1 > W or y1 > H: continue
                d = dark[y0:y1, x0:x1].mean(); s = sil[y0:y1, x0:x1].mean()
                if d > 0.2: v = 128 + int(min(127, 40 + d * 160))
                elif s > 0.5: v = 60
                else: continue
                cells.setdefault((gx, gy), [0] * len(frames))[fi] = v
    return cells

# each frame on its own: the cells it covers, (x, y, value)
def frame_cells(pitch):
    per = [[] for _ in frames]
    for (gx, gy), vals in sample(pitch).items():
        for f, v in enumerate(vals):
            if v: per[f].append((gx, gy, v))
    return per

lo, hi = 2.0, 12.0
for _ in range(30):
    mid = (lo + hi) / 2
    if max(len(p) for p in frame_cells(mid)) > CELLS: lo = mid
    else: hi = mid
pitch = hi
per = frame_cells(pitch)
M = max(len(p) for p in per)

# Every frame gets exactly M dots (a short frame repeats some of its dots), and dot k in one frame
# is matched to dot k in the others, so the page can slide each dot from pose to pose. Matching is
# an assignment that keeps each dot close to where its neighbours in the cycle put it, with ink
# kept on ink.
from scipy.optimize import linear_sum_assignment
rng = np.random.default_rng(7)
P = []
for p in per:
    a = np.array(p, float)
    if len(a) < M: a = np.vstack([a, a[rng.choice(len(a), M - len(a))]])
    P.append(a)
def match(points, target):
    d = ((points[:, None, :2] - target[None, :, :2]) ** 2).sum(-1)
    d += 9.0 * ((points[:, None, 2] >= 128) != (target[None, :, 2] >= 128))
    r, c = linear_sum_assignment(d)
    out = np.empty_like(points); out[c] = points[r]
    return out
CYC = [1, 2, 3, 4, 5, 6]
for i in range(1, len(CYC)): P[CYC[i]] = match(P[CYC[i]], P[CYC[i - 1]])
for it in range(4):
    for i, f in enumerate(CYC):
        if i == 0: continue
        prev, nxt = P[CYC[i - 1]], P[CYC[(i + 1) % len(CYC)]]
        tgt = prev.copy(); tgt[:, :2] = (prev[:, :2] + nxt[:, :2]) / 2
        P[f] = match(P[f], tgt)
    move = [float(np.hypot(*(P[CYC[(i + 1) % 6]][:, :2] - P[CYC[i]][:, :2]).T).mean()) for i in range(6)]
    print('pass', it, 'mean cell move per step', [round(m, 2) for m in move])
mean = np.mean([P[f] for f in CYC], 0)
P[0] = match(P[0], mean)

X = np.array([P[f][:, 0] for f in range(len(frames))], np.int8)
Y = np.array([P[f][:, 1] for f in range(len(frames))], np.int8)
Vv = np.array([P[f][:, 2] for f in range(len(frames))], np.uint8)
blob = lambda a: base64.b64encode(a.tobytes()).decode()
js = ('// Generated by tools/leopard-frames.py from tools/leopard-reference.webp. Do not edit.\n'
      '// COUNT dots in FRAMES poses; X, Y in grid steps of PITCH drawing px; V: 0 none, 1-127 coat, 128+ ink.\n'
      f'export const PITCH = {pitch:.4f};\nexport const COUNT = {M};\nexport const FRAMES = {len(frames)};\n'
      f'export const X = "{blob(X)}";\nexport const Y = "{blob(Y)}";\nexport const V = "{blob(Vv)}";\n')
open(OUT, 'w').write(js)
print('pitch', round(pitch, 3), 'dots', M, 'bytes', len(js))
